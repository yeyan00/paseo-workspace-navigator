export type Language = keyof typeof messages;
export type Messages = { [Key in keyof typeof messages.en]: string };

export function relativeTime(at: number, now: number, t: Messages): string {
  if (!at) return t.unknown;
  const minutes = Math.max(0, Math.floor((now - at) / 60_000));
  if (minutes < 1) return t.justNow;
  if (minutes < 60) return `${minutes}${t.minutes}`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours}${t.hours}`;
  return `${Math.floor(hours / 24)}${t.days}`;
}
